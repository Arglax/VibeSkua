#!/usr/bin/env python3
"""
Writes firebase/firestore.rules, the Firestore rules of MoVibeSkua's own `movibeskua` Firebase
project, from the signal and screen lists in MoVibeSkua.Android/Usage/Signal.cs.

    python tools/generate_firestore_rules.py
    cd firebase && firebase deploy --only firestore:rules

Re-run and deploy whenever Signal.cs changes, before an APK that sends the new names ships: the
rules refuse a write that carries an unknown name.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIGNAL_FILE = os.path.join(ROOT, "MoVibeSkua.Android", "Usage", "Signal.cs")
RULES_FILE = os.path.join(ROOT, "firebase", "firestore.rules")

COLLECTION = "movibeskua_installs"
APP_ID = "movibeskua"
SCREEN_FIELDS = ["visits", "ms", "quick", "idle", "d5", "d15", "d60", "d180", "dmax"]
TOP_LEVEL_FIELDS = ["schema", "app", "lastSeen", "firstSeen", "appVersion", "appVersionCode", "country", "features", "screens", "days"]
# Time per UTC day, "dYYYYMMDD" -> {fg, run, bot} in ms. Rules cannot loop over map keys, so the day
# map is only capped in size (about five years of days) and checked to be a map.
MAX_DAYS = 2000


def enum_names(source, enum_name):
    match = re.search(r"public enum " + enum_name + r"\s*\{(.*?)\}", source, re.DOTALL)
    if not match:
        return []
    return re.findall(r"^\s{4}([A-Z][A-Z0-9_]*)\s*,?\s*$", match.group(1), re.MULTILINE)


def quote_list(items, indent):
    pad = " " * indent
    return "[\n" + ",\n".join(pad + "  '" + item + "'" for item in sorted(items)) + "\n" + pad + "]"


def rules_file(signals, screens):
    # Maps a client never wrote are missing, so they are read with get(..., {}).
    screen_checks = "\n".join(
        "          && (!('" + name + "' in screens) || screens." + name + ".keys().hasOnly(fields))"
        for name in sorted(screens)
    )
    return """// Generated by tools/generate_firestore_rules.py from MoVibeSkua.Android/Usage/Signal.cs; edit that, not this.
rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {

    // Deny everything that is not explicitly allowed below.
    match /{document=**} {
      allow read, write: if false;
    }

    // Usage counts, one document per anonymous install. Nothing client-side reads them back;
    // reporting runs through the Admin SDK.
    match /%s/{uid} {
      allow read: if false;

      allow delete: if request.auth != null && request.auth.uid == uid;

      allow create, update: if request.auth != null
        && request.auth.uid == uid
        && request.resource.data.schema == 1
        && request.resource.data.app == '%s'
        && request.resource.data.appVersion is string
        && request.resource.data.appVersion.size() <= 24
        && request.resource.data.appVersionCode is int
        && request.resource.data.country is string
        && request.resource.data.country.size() <= 7
        && request.resource.data.keys().hasOnly(%s)
        && request.resource.data.get('features', {}).keys().hasOnly(%s)
        && screensOk(request.resource.data.get('screens', {}), %s)
        && request.resource.data.get('days', {}) is map
        && request.resource.data.get('days', {}).size() <= %d;

      function screensOk(screens, fields) {
        return screens.keys().hasOnly(%s)
%s;
      }
    }
  }
}
""" % (
        COLLECTION,
        APP_ID,
        quote_list(TOP_LEVEL_FIELDS, 8),
        quote_list(signals, 8),
        "[" + ", ".join("'" + field + "'" for field in SCREEN_FIELDS) + "]",
        MAX_DAYS,
        quote_list(screens, 8),
        screen_checks,
    )


def main():
    with open(SIGNAL_FILE, encoding="utf-8") as handle:
        source = handle.read()

    signals = enum_names(source, "Signal")
    screens = enum_names(source, "Screen")
    if not signals or not screens:
        sys.exit("could not read the Signal and Screen enums in " + SIGNAL_FILE)

    with open(RULES_FILE, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(rules_file(signals, screens))
    print("wrote " + str(len(signals)) + " signals and " + str(len(screens)) + " screens to " + RULES_FILE)


main()
